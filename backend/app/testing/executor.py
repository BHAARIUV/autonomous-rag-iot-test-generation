"""
Phase 8 — the controlled test-action executor.

WHY (SECURITY):
    Nothing generated by an LLM is ever executed as code. The executor walks
    a closed list of `TestAction`s, validates each one's typed parameters,
    and dispatches it to a dedicated handler that only touches existing
    building blocks:
        SET_TEMPERATURE        -> deterministic set-point            (Phase 2)
        SET_SENSOR_STATUS      -> TemperatureSensorSimulator.go_*    (Phase 2)
        READ_SENSOR            -> TemperatureSensorSimulator.tick()  (Phase 2)
        INJECT_FAULT/CLEAR_FAULT -> FaultRegistry.make_fault + FaultInjector (Phase 4)
        MQTT_*                 -> MqttConnection + Phase 3 wire helpers (Phase 3)
    READING faults are applied on the next READ through the existing Phase 4
    `FaultInjectedSimulator` adapter (shared decision engine, no duplication).

WHAT:
    `execute(actions, test_case_id, requirement_id)` runs the validated actions
    sequentially under a bounded wall-clock budget, collects per-step
    `StepEvidence`, and returns one aggregated `ExecutionResult`. FAIL
    (assertion evaluated, expectation not met) is always distinct from ERROR
    (execution could not complete).

HOW (determinism):
    The simulator is Phase 2's seeded `TemperatureSensorSimulator`: same seed +
    same tick sequence => same readings. A controlled set-point (SET_TEMPERATURE)
    makes the device report exactly the commanded value on subsequent READs
    until it is changed, faulted, cleared, or reset. ASSERT_* steps are pure
    evaluations (app/testing/assertions.py) of the actually-observed value —
    never fabricated.

HOW TO VERIFY:
    See tests/unit/test_execution_executor.py and
    tests/integration/test_execution_full_chain.py.
"""

